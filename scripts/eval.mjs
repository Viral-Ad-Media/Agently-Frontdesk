// npm run eval: runs the eval set on the mock provider and writes docs/EVAL.md.
// For Meta numbers (tokens, cost, time), open /eval in the app with VITE_AI_PROVIDER=meta and press Run.
import { writeFileSync } from "node:fs";
import * as mock from "../src/gateway/providers/mock.js";
import { TENANTS } from "../src/lib/seed.js";
import { runEval, toMarkdown } from "../src/eval/runEval.js";

const res = await runEval({ ai: mock, tenants: TENANTS, onRow: (r) => console.log(`${r.correct ? "ok " : "NO "} ${r.id.padEnd(3)} ${r.status.padEnd(13)} expected ${r.expected}`) });
const md = `# Eval results\n\nGenerated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}. Same pipeline as the live chat: router, assessment, rate-card quote, reviewer pass (up to 3), coded checks, checklist coverage.\n\n${toMarkdown(res, "mock (deterministic rehearsal, no tokens)")}\nMeta numbers: run /eval in the app with the Meta provider; it shows tokens, cost (when prices are configured) and time per job.\n`;
writeFileSync(new URL("../docs/EVAL.md", import.meta.url), md);
console.log(`\n${res.correct}/${res.total} correct. Wrote docs/EVAL.md`);
process.exit(res.correct === res.total ? 0 : 1);
